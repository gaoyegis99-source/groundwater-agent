from __future__ import annotations

import json
from pathlib import Path

import pytest

from scripts.development.capability_inventory import (
    CapabilityInventoryRefusal,
    build_capability_inventory,
    generate_capability_inventory,
    render_capability_inventory,
)
from scripts.development.product_selection import load_selected_product_by_id


def _json(path: Path) -> dict[str, object]:
    return json.loads(path.read_text(encoding="utf-8"))


def test_inventory_is_derived_from_domain_catalog_and_product_ui() -> None:
    repository = Path(__file__).resolve().parents[2]
    product_manifest = repository / "products/groundwater/product-manifest.json"
    inventory = build_capability_inventory(repository, product_manifest)
    selected = load_selected_product_by_id(repository, "groundwater")
    domain = _json(selected.domain.root / "domain-manifest.json")
    catalog = _json(repository / "packages/operator-pack/catalog/index.json")
    product_ui = _json(selected.manifest_path.parent / selected.manifest["uiProfile"]["path"])

    summary = inventory["summary"]
    assert summary["modelCount"] == len(domain["executableModels"])
    assert summary["workflowCount"] == len(domain["workflowDefinitions"])
    assert summary["operatorCount"] == len(catalog["operators"])
    assert summary["uiModelCount"] == len(product_ui["models"])
    assert summary["exampleCount"] == len(product_ui["examples"])
    assert (
        inventory["sources"]["operatorCatalog"]["catalogDigest"]
        == (catalog["catalogDigest"])
    )
    assert {item["modelId"] for item in inventory["models"]} == set(
        product_ui["models"]
    )
    assert {item["identity"] for item in inventory["operators"]} == {
        f"{item['id']}@{item['version']}" for item in catalog["operators"]
    }

    rendered = render_capability_inventory(inventory)
    assert rendered.startswith("<!-- Generated by scripts/development/")
    assert "不要手工编辑" in rendered
    for model_id in product_ui["models"]:
        assert f"`{model_id}`" in rendered
    for operator in catalog["operators"]:
        assert f"`{operator['id']}@{operator['version']}`" in rendered


def test_inventory_generation_is_deterministic_and_check_detects_drift(
    tmp_path: Path,
) -> None:
    repository = Path(__file__).resolve().parents[2]
    product_manifest = repository / "products/groundwater/product-manifest.json"
    output = tmp_path / "current-capability-inventory.md"

    updated = generate_capability_inventory(
        repository_root=repository,
        product_manifest_path=product_manifest,
        output_path=output,
        check=False,
    )
    assert updated["status"] == "UPDATED"
    assert output.is_file()
    assert (
        generate_capability_inventory(
            repository_root=repository,
            product_manifest_path=product_manifest,
            output_path=output,
            check=True,
        )["status"]
        == "PASS"
    )

    output.write_text(output.read_text(encoding="utf-8") + "stale\n", encoding="utf-8")
    with pytest.raises(
        CapabilityInventoryRefusal,
        match="CAPABILITY_INVENTORY_OUT_OF_DATE",
    ):
        generate_capability_inventory(
            repository_root=repository,
            product_manifest_path=product_manifest,
            output_path=output,
            check=True,
        )


